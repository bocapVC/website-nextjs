import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { LockClosed } from "@/components/icons/LockClosed";
import { Badge } from "@/components/ui/Badge";
import { Card } from "@/components/ui/Card";
import { Section } from "@/components/ui/Section";
import { DownloadAction } from "@/components/sections/publicaciones/DownloadAction";
import { Markdown } from "@/components/sections/publicaciones/Markdown";
import { ShareLinks } from "@/components/sections/publicaciones/ShareLinks";
import { SITE } from "@/config/nav";
import { getPublicacion, getPublicaciones } from "@/lib/getPublicaciones";
import { OG_IMAGE_SIZE, pageMetadata } from "@/lib/metadata";
import { publicacionMeta, publicacionPath } from "@/lib/publicaciones";

// Every publication is prerendered from src/data/publicaciones; any other slug is a 404.
export const dynamicParams = false;

export function generateStaticParams() {
  return getPublicaciones().map(({ slug }) => ({ slug }));
}

interface PageProps {
  params: Promise<{ slug: string }>;
}

export async function generateMetadata({ params }: PageProps): Promise<Metadata> {
  const publicacion = getPublicacion((await params).slug);
  if (!publicacion) return {};
  const path = publicacionPath(publicacion);
  return pageMetadata({
    title: publicacion.title,
    description: publicacion.excerpt,
    path,
    // Generated by ./opengraph-image.tsx; referenced explicitly, see pageMetadata.
    image: { url: `${path}/opengraph-image`, ...OG_IMAGE_SIZE, alt: publicacion.title },
    article: {
      publishedTime: publicacion.date,
      authors: publicacion.author ? [publicacion.author] : undefined,
    },
  });
}

export default async function PublicacionPage({ params }: PageProps) {
  const publicacion = getPublicacion((await params).slug);
  if (!publicacion) notFound();

  const path = publicacionPath(publicacion);
  const url = `${SITE.url}${path}`;
  const jsonLd = {
    "@context": "https://schema.org",
    "@type": publicacion.body ? "BlogPosting" : "Article",
    headline: publicacion.title,
    description: publicacion.excerpt,
    datePublished: publicacion.date,
    url,
    mainEntityOfPage: url,
    image: `${url}/opengraph-image`,
    inLanguage: "es",
    articleSection: publicacion.category,
    author: publicacion.author
      ? { "@type": "Person", name: publicacion.author }
      : { "@type": "Organization", name: SITE.name, url: SITE.url },
    publisher: {
      "@type": "Organization",
      name: SITE.name,
      url: SITE.url,
      logo: { "@type": "ImageObject", url: `${SITE.url}/logo.png` },
    },
  };

  return (
    <Section firstOnPage>
      <script
        type="application/ld+json"
        // `<` escaped so editor-written text can't close the script tag (Next.js JSON-LD guide).
        dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd).replace(/</g, "\\u003c") }}
      />
      <article className="mx-auto max-w-3xl">
        <Link
          href="/publicaciones"
          className="text-sm font-semibold text-teal hover:text-teal-strong hover:underline"
        >
          ← Publicaciones
        </Link>

        <header className="mt-8 flex flex-col gap-4">
          <div className="flex flex-wrap items-center gap-2">
            <Badge>{publicacion.category}</Badge>
          </div>
          <h1 className="font-serif text-heading-lg font-bold leading-tight text-ink">
            {publicacion.title}
          </h1>
          <p className="text-xs uppercase tracking-wide text-ink-soft">
            {publicacion.author ? `${publicacion.author} · ` : null}
            <time dateTime={publicacion.date}>{publicacionMeta(publicacion)}</time>
          </p>
          <p className="text-lg leading-relaxed text-ink-soft">{publicacion.excerpt}</p>
        </header>

        {publicacion.body ? (
          <div className="mt-10 border-t border-line pt-10">
            <Markdown source={publicacion.body} />
          </div>
        ) : null}

        {publicacion.file ? (
          <Card className="mt-12 flex flex-wrap items-center justify-between gap-4">
            <div className="flex flex-col gap-2">
              <p className="font-serif text-xl font-bold text-ink">Documento completo</p>
              {publicacion.access === "protected" ? (
                <Badge tone="gold" className="self-start">
                  <LockClosed className="h-3.5 w-3.5" />
                  Requiere correo
                </Badge>
              ) : null}
            </div>
            <DownloadAction publicacion={publicacion} />
          </Card>
        ) : null}

        <div className="mt-12 border-t border-line pt-8">
          <ShareLinks url={url} title={publicacion.title} />
        </div>
      </article>
    </Section>
  );
}
